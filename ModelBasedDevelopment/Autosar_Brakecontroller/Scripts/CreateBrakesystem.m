clc;
clear;

model = 'BrakeController_MBD';

% open model
open_system(model);

% Save model
save_system(model, [model '.slx']);

disp('Brake Controller model created.');

%parametes 
K = 2;
BrakePressure_Max = 100;

Ts = 0.001;

%% Add ports

add_block('simulink/Ports & Subsystems/In1', ...
    [model '/VehicleSpeed'], ...
    'Position', [50 80 80 100]);

add_block('simulink/Ports & Subsystems/In1', ...
    [model '/BrakeRequest'], ...
    'Position', [50 180 80 200]);

add_block('simulink/Ports & Subsystems/Out1', ...
    [model '/BrakePressure'], ...
    'Position', [650 130 680 150]);

add_block('simulink/Math Operations/Gain', ...
    [model '/BrakeGain'], ...
    'Gain', 'K', ...
    'Position', [180 70 250 110]);


add_block('simulink/Signal Routing/Switch', ...
    [model '/BrakeRequestSwitch'], ...
    'Threshold', '0.5', ...
    'Position', [350 100 400 160]);

add_block('simulink/Sources/Constant', ...
    [model '/ZeroPressure'], ...
    'Value', '0', ...
    'Position', [180 200 230 230]);

add_block('simulink/Discontinuities/Saturation', ...
    [model '/PressureSaturation'], ...
    'UpperLimit', 'BrakePressure_Max', ...
    'LowerLimit', '0', ...
    'Position', [470 110 550 150]);

%% Connect blocks

add_line(model, ...
    'VehicleSpeed/1', ...
    'BrakeGain/1');

add_line(model, ...
    'BrakeGain/1', ...
    'BrakeRequestSwitch/1');

add_line(model, ...
    'BrakeRequest/1', ...
    'BrakeRequestSwitch/2');

add_line(model, ...
    'ZeroPressure/1', ...
    'BrakeRequestSwitch/3');

add_line(model, ...
    'BrakeRequestSwitch/1', ...
    'PressureSaturation/1');

add_line(model, ...
    'PressureSaturation/1', ...
    'BrakePressure/1');

set_param(model, ...
    'SolverType', 'Fixed-step', ...
    'FixedStep', 'Ts');

save_system(model);

disp('Brake Controller model configured successfully.');